public class StudentFormatter {

    /**
     * Форматирует и выводит на консоль строку с данными об успеваемости студента.
     * Выделяет под фамилию 15 символов, под оценку 3 символа, под предмет - 10 символов.
     * 
     * @param lastName фамилия студента
     * @param grade    оценка (целое число)
     * @param subject  название учебного предмета
     */
    public static void printStudentGrade(String lastName, int grade, String subject) {
        // Форматирование: Студент [Фамилия] получил [оценка] по [предмету]
        // %-15s: строка с выравниванием по левому краю шириной 15 символов
        // %-3d: целое число шириной 3 символа
        // %-10s: строка шириной 10 символов
        String formattedString = String.format("Студент %-15s получил %-3d по %-10s", lastName, grade, subject);
        System.out.println(formattedString);
    }

    public static void main(String[] args) {
        System.out.println("Результаты успеваемости студентов (Задание №2):");
        System.out.println("==================================================================");

        // Пример вывода в соответствии с методическими указаниями
        printStudentGrade("Иванов", 5, "Математике");
        printStudentGrade("Петрова", 4, "Физике");
        printStudentGrade("Сидорова", 3, "Программированию");

        // Демонстрация для автора работы
        printStudentGrade("Лабынцев", 10, "ССП");
        printStudentGrade("Лабынцев", 9, "1С:Предприятие");

        System.out.println("==================================================================");
    }
}
