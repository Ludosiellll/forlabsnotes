package main

import "fmt"

// Лабораторная работа №7 по дисциплине "Современные системы программирования"
// Задание 2 (Приложение А, Вариант 14):
// Даны два целых числа a и b (a < b). Найти произведение всех целых чисел от a до b включительно.
// Группа: РС02-23
func main() {
	var a, b int

	fmt.Print("Введите целое число a: ")
	fmt.Scan(&a)

	fmt.Print("Введите целое число b (b > a): ")
	fmt.Scan(&b)

	if a >= b {
		fmt.Println("Ошибка: должно выполняться условие a < b!")
		return
	}

	var product int64 = 1
	for i := a; i <= b; i++ {
		product *= int64(i)
	}

	fmt.Printf("Произведение всех целых чисел от %d до %d включительно равно: %d\n", a, b, product)
}
